export const ALL_PSTAR_QUESTIONS: PSTARQuestion[] = PSTAR_SECTIONS.flatMap(s => s.questions);

export type PSTARFlashcard = {
  id: string;
  front: string;
  back: string;
  hint: string;
  material: string;
  difficulty: "easy" | "medium" | "hard";
};

const SECTION_DIFFICULTY: Record<number, "easy" | "medium" | "hard"> = {};
PSTAR_SECTIONS.forEach(s => { SECTION_DIFFICULTY[s.number] = s.difficulty; });

const SECTION_TITLE: Record<number, string> = {};
PSTAR_SECTIONS.forEach(s => { SECTION_TITLE[s.number] = s.title; });

export const PSTAR_FLASHCARDS: PSTARFlashcard[] = ALL_PSTAR_QUESTIONS.map(q => ({
  id: q.id,
  front: q.question,
  back: q.options[q.correct],
  hint: q.hint ?? "",
  material: SECTION_TITLE[q.section] ?? `Section ${q.section}`,
  difficulty: SECTION_DIFFICULTY[q.section] ?? "medium",
}));

export function getQuestionsBySection(sectionNumber: number): PSTARQuestion[] {
  return PSTAR_SECTIONS.find(s => s.number === sectionNumber)?.questions ?? [];
}

export function getRandomQuestions(count: number, sectionNumber?: number): PSTARQuestion[] {
  const pool = sectionNumber ? getQuestionsBySection(sectionNumber) : ALL_PSTAR_QUESTIONS;
  const shuffled = [...pool].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, Math.min(count, shuffled.length));
}
